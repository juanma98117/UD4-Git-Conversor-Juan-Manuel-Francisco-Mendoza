    /**
     * Convierte grados Celsius a Fahrenheit.
     * Fórmula: F = (C × 9/5) + 32
     */
    public static double celsiusAFahrenheit(double celsius) {
        return (celsius * 9.0 / 5.0) + 32;
    }

